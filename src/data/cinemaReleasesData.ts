/**
 * Helper to compute an ISO YYYY-MM-DD date relative to today IST.
 * Ensures the date system is dynamic and never goes stale.
 */
function relDate(daysFromToday: number): string {
  const todayStr = getTodayIST();
  const [y, m, d] = todayStr.split("-").map(Number);
  const date = new Date(Date.UTC(y, m - 1, d + daysFromToday));
  return date.toISOString().split("T")[0];
}

