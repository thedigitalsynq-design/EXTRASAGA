export type LeaderboardSortDimension = "net" | "open" | "ww" | "os";

export function getYearlyLeaderboard(
  year: number = 2026,
  sortBy: LeaderboardSortDimension = "net"
): YearlyBoxOfficeLeaderboardItem[] {
  const records = YEARLY_LEADERBOARD_RECORDS[year] || YEARLY_LEADERBOARD_RECORDS[2026];

  const sorted = [...records].sort((a, b) => {
    switch (sortBy) {
      case "open":
        return b.openingDayNettCrores - a.openingDayNettCrores;
      case "ww":
        return b.worldwideGrossCrores - a.worldwideGrossCrores;
      case "os":
        return b.overseasGrossUSDMillions - a.overseasGrossUSDMillions;
      case "net":
      default:
        return b.indiaNettCrores - a.indiaNettCrores;
    }
  });

  return sorted.map((item, index) => ({
    ...item,
    rank: index + 1,
  }));
}

export function getYearlyAggregateStats(year: number = 2026) {
  const items = YEARLY_LEADERBOARD_RECORDS[year] || YEARLY_LEADERBOARD_RECORDS[2026];
  const totalIndiaNet = items.reduce((sum, item) => sum + item.indiaNettCrores, 0);
  const totalWorldwide = items.reduce((sum, item) => sum + item.worldwideGrossCrores, 0);
  const hitsOrBetterCount = items.filter(
    (item) =>
      item.verdict === "all_time_blockbuster" ||
      item.verdict === "blockbuster" ||
      item.verdict === "superhit" ||
      item.verdict === "hit"
  ).length;

  const topGrosser = [...items].sort((a, b) => b.worldwideGrossCrores - a.worldwideGrossCrores)[0];

  return {
    year,
    filmsTrackedCount: items.length,
    totalIndiaNetCrores: Number(totalIndiaNet.toFixed(2)),
    totalWorldwideCrores: Number(totalWorldwide.toFixed(2)),
    hitsOrBetterCount,
    topGrosserName: topGrosser ? topGrosser.movieTitleEn : "N/A",
    topGrosserCollection: topGrosser ? `₹${topGrosser.worldwideGrossCrores.toLocaleString("en-IN")} Cr` : "N/A",
  };
}

