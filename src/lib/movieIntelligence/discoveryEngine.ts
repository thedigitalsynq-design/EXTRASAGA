export interface RawDiscoveredCandidate {
  rawId: string;
  title: string;
  titleEn: string;
  slug: string;
  industry: FilmIndustry;
  language: LanguageCode;
  genres: string[];
  director: string;
  producers: string[];
  productionCompany: string;
  distributionCompany: string;
  cast: { name: string; role: string; characterName?: string }[];
  synopsis: string;
  introduction?: string;
  posterImage: string;
  bannerImage?: string;
  censorRating?: string;
  runtimeMinutes?: number;
  runtimeFormatted?: string;
  trailerYoutubeId?: string;
  isFeatured?: boolean;
  observations: ReleaseDateObservation[];
  postponementNotice?: {
    isPostponed: boolean;
    originalDate: string;
    newAnnouncedDate?: string;
    reason: string;
  };
}

/**
 * Creates an internal source observation.
 * Note: Provider identities and internal metadata are kept server-side only.
 */
function createObservation(
  sourceId: string,
  sourceType: SourceType,
  weight: number,
  observedDate: string,
  isOfficialAnnouncement: boolean,
  notes?: string
): ReleaseDateObservation {
  return {
    sourceId,
    sourceType,
    sourceAuthorityWeight: weight,
    observedDate,
    observedAt: new Date().toISOString(),
    isOfficialAnnouncement,
    notes,
  };
}

